import { screen, within, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, expect, it, vi } from 'vitest'
import { toDataURL } from 'qrcode'
import { adminFixture, resourceId, qrId, publicToken, stamps, tenantA, customerId, siteId } from '../../test/adminFixture'
import { qrPayload } from './qrPayload'

vi.mock('qrcode', () => ({ toDataURL: vi.fn(async () => 'data:image/png;base64,synthetic-test-image') }))
afterEach(() => { vi.unstubAllGlobals(); vi.unstubAllEnvs() })
const qr = { id: qrId, trailerId: resourceId, publicToken, operationalNumber: 'T114', active: true, issuedAt: stamps.createdAt, revokedAt: null }

it('QR issue, explicit confirmed revoke, retained history and explicit reissue never implicitly replace an active QR', async () => {
  const user = userEvent.setup(); const f = adminFixture(`/admin/trailers/${resourceId}`)
  await user.click(await screen.findByRole('button', { name: 'Issue QR' }))
  await screen.findByRole('button', { name: 'Revoke QR' })
  expect(screen.getByRole('button', { name: 'Issue QR' })).toBeDisabled()
  expect(f.requests.filter(r => r.method === 'POST')).toHaveLength(1)
  await user.click(screen.getByRole('button', { name: 'Revoke QR' }))
  expect(within(screen.getByRole('dialog')).getByRole('button', { name: 'Cancel' })).toHaveFocus()
  await user.keyboard('{Escape}')
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(f.requests.filter(r => r.method === 'POST')).toHaveLength(1)
  await user.click(screen.getByRole('button', { name: 'Revoke QR' }))
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Revoke QR' }))
  expect(await screen.findByText('Historical')).toBeInTheDocument()
  expect(screen.queryByRole('button', { name: 'Print active QR' })).not.toBeInTheDocument()
  expect(f.qrs()[0]!.active).toBe(false)
  await user.click(screen.getByRole('button', { name: 'Issue QR' }))
  await screen.findByRole('button', { name: 'Revoke QR' })
  const actions = f.requests.filter(r => r.method === 'POST')
  expect(actions).toHaveLength(3)
  expect(actions[1]!.path).toBe(`/api/v1/tenants/${tenantA}/trailers/${resourceId}/qr-identities/${qrId}/revocation`)
  expect(actions.every(r => r.body === undefined)).toBe(true)
})
it('QR conflict is visible and never triggers implicit revocation', async () => {
  const user = userEvent.setup(); const f = adminFixture(`/admin/trailers/${resourceId}`)
  await screen.findByRole('button', { name: 'Issue QR' })
  f.fail({ status: 409, code: 'RESOURCE_CONFLICT' })
  await user.click(screen.getByRole('button', { name: 'Issue QR' }))
  expect(await screen.findByText(/This change conflicts with existing data/)).toBeInTheDocument()
  expect(f.requests.filter(r => r.method === 'POST')).toHaveLength(1)
  expect(f.requests.some(r => r.path.endsWith('/revocation'))).toBe(false)
})
it('active QR print preview encodes configured HTTPS URL and prints only QR plus operational number', async () => {
  vi.stubEnv('VITE_QR_PUBLIC_BASE_URL', 'https://labels.example.test')
  const user = userEvent.setup(); const f = adminFixture(`/admin/trailers/${resourceId}`); f.qrs([qr])
  const print = vi.spyOn(window, 'print').mockImplementation(() => {})
  const log = vi.spyOn(console, 'log')
  await user.click(await screen.findByRole('button', { name: 'Print active QR' }))
  const label = await screen.findByLabelText('Trailer label')
  expect(within(label).getByText('T114')).toBeInTheDocument()
  expect(within(label).getByRole('img', { name: 'Trailer QR code' })).toBeInTheDocument()
  expect(label.textContent).not.toContain(tenantA)
  expect(label.textContent).not.toContain(customerId)
  expect(label.textContent).not.toContain(resourceId)
  expect(label.textContent).not.toContain(publicToken)
  expect(toDataURL).toHaveBeenCalledWith(`https://labels.example.test/t/${publicToken}`, expect.objectContaining({ margin: 4 }))
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Print' }))
  expect(print).toHaveBeenCalledOnce(); expect(log).not.toHaveBeenCalled()
})
it('missing QR host disables print without preventing QR management', async () => {
  const f = adminFixture(`/admin/trailers/${resourceId}`); f.qrs([qr])
  expect(await screen.findByRole('button', { name: 'Print active QR' })).toBeDisabled()
  expect(screen.getByText(/valid public QR base URL has not been configured/)).toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'Revoke QR' })).toBeEnabled()
  expect(qrPayload(undefined, publicToken)).toBeUndefined()
  expect(qrPayload('http://localhost:5173/', publicToken)).toBe(`http://localhost:5173/t/${publicToken}`)
})
it('all seven Trailer filters are sent together, with current Location selected from an existing Site', async () => {
  const user = userEvent.setup(); const f = adminFixture('/admin/trailers')
  const form = within(await screen.findByRole('form', { name: 'Trailer filters' }))
  await user.type(form.getByLabelText('Operational number'), ' t114 ')
  await waitFor(() => expect(form.getByRole('option', { name: 'Original customers' })).toBeInTheDocument())
  await user.selectOptions(form.getByLabelText('Designated Customer filter'), customerId)
  await user.selectOptions(form.getByLabelText('Location state'), 'AT_LOCATION')
  await user.selectOptions(form.getByLabelText('Site for location filter'), siteId)
  await waitFor(() => expect(form.getByRole('option', { name: 'Original locations' })).toBeInTheDocument())
  await user.selectOptions(form.getByLabelText('Current location'), resourceId)
  await user.selectOptions(form.getByLabelText('Load state'), 'LOADED')
  await user.selectOptions(form.getByLabelText('Serviceability'), 'IN_SERVICE')
  await user.selectOptions(form.getByLabelText('Active filter'), 'true')
  await user.click(form.getByRole('button', { name: 'Apply filters' }))
  await waitFor(() => expect(f.requests.some(r => r.path.includes('/trailers?'))).toBe(true))
  const path = f.requests.find(r => r.path.includes('/trailers?'))!.path
  const values = Object.fromEntries(new URL(`https://example.test${path}`).searchParams)
  expect(values).toEqual({ operationalNumber: ' t114 ', designatedCustomerId: customerId, locationState: 'AT_LOCATION', currentLocationId: resourceId, loadState: 'LOADED', serviceabilityState: 'IN_SERVICE', active: 'true' })
  await user.click(form.getByRole('button', { name: 'Out of Service' }))
  await waitFor(() => expect(f.requests.some(r => r.path.includes('serviceabilityState=OUT_OF_SERVICE'))).toBe(true))
  await user.click(form.getByRole('button', { name: 'Location Unknown' }))
  await waitFor(() => expect(f.requests.some(r => r.path.includes('locationState=LOCATION_UNKNOWN'))).toBe(true))
})
